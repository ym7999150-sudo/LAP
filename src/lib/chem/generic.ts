/**
 * Rule-based reaction generator. Every pair of substances (and every substance heated or
 * added to water) yields either a balanced reaction or a scientifically stated "no reaction".
 *
 * Rules (school level): neutralisation, acid + carbonate, acid + metal (activity series),
 * acid + metal oxide, metal displacement, double-displacement precipitation (solubility rules),
 * ammonium salt + strong base, reactive metal / basic oxide + water, thermal decomposition.
 */
import { balance } from "./balance";
import { compositionOf, ionicId, oxideId, type Comp } from "./composition";
import { ANIONS, CATIONS, ION_METAL, METAL_ION, aboveHydrogen, rank, reactsWithColdWater, solubility, type Bi } from "./ions";
import type { ReactionDef, ReactionType, SafetyClass } from "./reactions";
import { getSubstance } from "./substances";

/** Generated reaction definitions, keyed by id, so UI and server can look them up after a replay. */
export const GENERATED = new Map<string, ReactionDef>();

export type Outcome = { kind: "reaction"; def: ReactionDef } | { kind: "none"; explanation: Bi };

const METAL_ID: Record<string, string> = { Zn: "zn", Mg: "mg", Fe: "fe", Cu: "cu", Ag: "ag", Na: "na", K: "k", Ca: "ca", Al: "al", Hg: "hg", Pb: "pb", Ni: "ni", Sn: "sn" };
const none = (en: string, ar: string): Outcome => ({ kind: "none", explanation: { en, ar } });
const nameOf = (id: string) => getSubstance(id)?.name ?? { en: id, ar: id };
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

function build(
  key: string,
  types: ReactionType[],
  reactants: string[],
  products: string[],
  opts: { gas?: string; precipitate?: string; deposit?: string; thermal: "exothermic" | "endothermic" | "slight"; explanation: Bi; colorChange?: Bi; minTempC?: number; waterIsSolvent?: boolean; deltaH?: number },
): Outcome {
  const f = (id: string) => getSubstance(id)!.formula!;
  const coeffs = balance(reactants.map(f), products.map(f));
  if (!coeffs) return none("No balanced reaction exists for these substances under these rules.", "لا يوجد تفاعل موزون لهذه المواد وفق هذه القواعد.");
  const all = [...reactants, ...products].map((id) => getSubstance(id)!);
  const safety: SafetyClass = all.some((s) => s.virtualOnly) || reactants.some((id) => ["na", "k", "hg"].includes(id)) ? "virtual-only" : all.some((s) => s.hazards.some((h) => h === "toxic" || h === "corrosive")) ? "supervised" : "school-safe";
  const def: ReactionDef = {
      id: `gen:${key}`,
      types,
      reactants: reactants.map((id, i) => ({ id, coeff: coeffs.r[i]! })),
      products: products.map((id, i) => ({ id, coeff: coeffs.p[i]! })),
      conditions: { minTempC: opts.minTempC, waterIsSolvent: opts.waterIsSolvent },
      observations: { gas: opts.gas, precipitate: opts.precipitate, deposit: opts.deposit, thermal: opts.thermal, colorChange: opts.colorChange },
      deltaH: opts.deltaH,
      explanation: opts.explanation,
      safety,
      provenance: "Generated by LabVerse rules (solubility rules, activity series); equation balanced automatically.",
  };
  GENERATED.set(def.id, def);
  return { kind: "reaction", def };
}

type Ionic = Extract<Comp, { kind: "ionic" }>;
const isAcid = (c?: Comp): boolean => c?.kind === "ionic" && c.cat === "H";
const isBase = (c?: Comp): boolean => c?.kind === "ionic" && c.an === "OH" && c.cat !== "H";
const isIonic = (c?: Comp): c is Extract<Comp, { kind: "ionic" }> => c?.kind === "ionic";
const soluble = (c: Extract<Comp, { kind: "ionic" }>) => solubility(c.cat, c.an).soluble;

function precipitateText(id: string): Bi {
  const s = getSubstance(id)!;
  return { en: `A precipitate of ${s.name.en.toLowerCase()} forms.`, ar: `يتكون راسب من ${s.name.ar}.` };
}

/** Outcome of mixing two substances in the same container. */
export function pairOutcome(a: string, b: string): Outcome {
  if (a === b) return none("Same substance — it simply mixes.", "نفس المادة — تختلط فقط.");
  let ca: Comp | undefined = compositionOf(a);
  let cb: Comp | undefined = compositionOf(b);
  if (!ca || !cb) return none("Physical mixture: no chemical reaction between these substances.", "خليط فيزيائي: لا يحدث تفاعل كيميائي بين هاتين المادتين.");

  if (ca.kind === "indicator" || cb.kind === "indicator") return none("The indicator only changes colour according to the pH; it takes no other part.", "الدليل يغيّر لونه فقط حسب الرقم الهيدروجيني ولا يشارك في تفاعل آخر.");
  if (ca.kind === "inert" || cb.kind === "inert") {
    const inert = (ca.kind === "inert" ? ca : cb) as Extract<Comp, { kind: "inert" }>;
    if (inert.why === "organic") return none("Sugar/alcohol do not react with this substance at room temperature; they just mix or dissolve.", "السكر والكحول لا يتفاعلان مع هذه المادة في درجة حرارة الغرفة؛ يختلطان أو يذوبان فقط.");
    if (inert.why === "catalyst") return none("Manganese(IV) oxide is a catalyst; it only speeds up the decomposition of hydrogen peroxide.", "ثاني أكسيد المنجنيز عامل حفاز؛ يسرّع فقط تحلل فوق أكسيد الهيدروجين.");
    if (inert.why === "peroxide") return none("Dilute hydrogen peroxide does not react with this substance at room temperature (it needs a catalyst such as MnO₂ to decompose).", "فوق أكسيد الهيدروجين المخفف لا يتفاعل مع هذه المادة في درجة حرارة الغرفة (يحتاج عاملاً حفازاً مثل MnO₂ ليتحلل).");
    if (inert.why === "gas") return none("This gas escapes from the open container and does not react here.", "هذا الغاز يتصاعد من الوعاء المفتوح ولا يتفاعل هنا.");
    return none("Sulfur does not react with this substance at room temperature; heating is needed for combination with metals.", "الكبريت لا يتفاعل مع هذه المادة في درجة حرارة الغرفة؛ يلزم التسخين ليتحد مع الفلزات.");
  }
  if (ca.kind === "water" || cb.kind === "water") return waterOutcome(ca.kind === "water" ? b : a) ?? none("It dissolves or mixes with water without a chemical reaction.", "يذوب أو يختلط بالماء دون تفاعل كيميائي.");

  // ---- acid rules
  if (isAcid(cb) && !isAcid(ca)) {
    [a, b] = [b, a];
    [ca, cb] = [cb, ca];
  }
  if (isIonic(ca) && isAcid(ca)) {
    const acid: Ionic = ca;
    if (isAcid(cb)) return none("Two acids do not neutralise each other — both supply H⁺ ions.", "الحمضان لا يتعادلان — كلاهما يعطي أيونات H⁺.");
    if (isIonic(cb) && isBase(cb)) {
      const salt = ionicId(cb.cat, acid.an);
      const sol = solubility(cb.cat, acid.an);
      return build(`neut:${a}:${b}`, ["neutralization", "double-displacement"], [a, b], [salt, "water"], {
        thermal: "exothermic",
        deltaH: -57.6 * ionicCountsOH(cb.cat),
        precipitate: sol.soluble ? undefined : salt,
        explanation: { en: `Neutralisation: H⁺ from the acid and OH⁻ from the base form water, leaving ${nameOf(salt).en.toLowerCase()}.`, ar: `تعادل: تتحد أيونات H⁺ من الحمض مع OH⁻ من القاعدة مكونة ماء، ويتبقى ${nameOf(salt).ar}.` },
        colorChange: sol.soluble ? undefined : precipitateText(salt),
      });
    }
    if (cb.kind === "ionic" && (cb.an === "CO3" || cb.an === "HCO3")) {
      const salt = ionicId(cb.cat, acid.an);
      return build(`carb:${a}:${b}`, ["acid-carbonate"], [a, b], [salt, "water", "co2"], {
        gas: "co2",
        thermal: "slight",
        precipitate: solubility(cb.cat, acid.an).soluble ? undefined : salt,
        explanation: { en: `Acid + carbonate → salt + water + carbon dioxide (effervescence). Salt formed: ${nameOf(salt).en.toLowerCase()}.`, ar: `حمض + كربونات ← ملح + ماء + ثاني أكسيد الكربون (فوران). الملح الناتج: ${nameOf(salt).ar}.` },
      });
    }
    if (cb.kind === "metal") {
      const m = cb.el;
      if (!aboveHydrogen(m)) return none(`${cap(m === "Hg" ? "mercury" : nameOf(b).en)} is below hydrogen in the activity series, so it does not displace hydrogen from this dilute acid.`, `${nameOf(b).ar} يلي الهيدروجين في متسلسلة النشاط الكيميائي، فلا يحل محله في هذا الحمض المخفف.`);
      const ion = METAL_ION[m]!;
      const salt = ionicId(ion, acid.an);
      return build(`acidmetal:${a}:${b}`, ["acid-metal", "single-displacement", "redox"], [b, a], [salt, "h2"], {
        gas: "h2",
        thermal: "exothermic",
        precipitate: solubility(ion, acid.an).soluble ? undefined : salt,
        explanation: { en: `${nameOf(b).en} is above hydrogen in the activity series, so it displaces hydrogen: bubbles of hydrogen gas and ${nameOf(salt).en.toLowerCase()} form.`, ar: `${nameOf(b).ar} يسبق الهيدروجين في متسلسلة النشاط فيحل محله: تتصاعد فقاعات الهيدروجين ويتكون ${nameOf(salt).ar}.` },
      });
    }
    if (cb.kind === "oxide") {
      const salt = ionicId(cb.cat, acid.an);
      return build(`acidox:${a}:${b}`, ["neutralization"], [a, b], [salt, "water"], {
        thermal: "exothermic",
        explanation: { en: `A metal oxide is a base: it neutralises the acid, forming ${nameOf(salt).en.toLowerCase()} and water.`, ar: `أكسيد الفلز قاعدي: يعادل الحمض مكوناً ${nameOf(salt).ar} وماء.` },
      });
    }
    if (isIonic(cb)) return doubleDisplacement(a, acid, b, cb);
  }

  // ---- metal rules
  if (cb.kind === "metal" && ca.kind !== "metal") {
    [a, b] = [b, a];
    [ca, cb] = [cb, ca];
  }
  if (ca.kind === "metal") {
    const m = ca.el;
    if (cb.kind === "metal") return none("Two metals do not react with each other at room temperature; they just form a mixture.", "الفلزان لا يتفاعلان في درجة حرارة الغرفة؛ يكوّنان خليطاً فقط.");
    if (cb.kind === "oxide") return none("No reaction at room temperature (metal–oxide displacement such as the thermite reaction needs very high temperatures).", "لا يحدث تفاعل في درجة حرارة الغرفة (إحلال الفلز في الأكسيد مثل تفاعل الثرميت يحتاج حرارة عالية جداً).");
    if (isIonic(cb)) {
      if (isBase(cb)) return none("Metals do not react with dilute alkali at room temperature (amphoteric Al and Zn need hot concentrated alkali, not modelled).", "الفلزات لا تتفاعل مع القلويات المخففة في درجة حرارة الغرفة (Al و Zn المترددان يحتاجان قلوياً مركزاً ساخناً، غير مُنمذج).");
      if (!soluble(cb)) return none("The salt is an insoluble solid, so the metal cannot reach its ions — no displacement.", "الملح صلب غير ذائب فلا يصل الفلز إلى أيوناته — لا يحدث إحلال.");
      const saltMetal = ION_METAL[cb.cat]!;
      if (reactsWithColdWater(m)) return none(`${nameOf(a).en} reacts with the water in the solution first (forming a hydroxide and hydrogen), rather than displacing the metal.`, `${nameOf(a).ar} يتفاعل أولاً مع ماء المحلول (مكوناً هيدروكسيداً وهيدروجين) بدلاً من إحلال الفلز.`);
      if (rank(m) < rank(saltMetal)) {
        const newSalt = ionicId(METAL_ION[m]!, cb.an);
        const deposit = METAL_ID[saltMetal]!;
        const fade = CATIONS[cb.cat]!.color;
        return build(`disp:${a}:${b}`, ["single-displacement", "redox"], [a, b], [newSalt, deposit], {
          deposit,
          thermal: "slight",
          colorChange: fade ? { en: "The solution's colour fades as the coloured ions are used up; metal deposits on the surface.", ar: "يبهت لون المحلول مع استهلاك الأيونات الملونة؛ ويترسب فلز على السطح." } : { en: "Metal deposits on the surface.", ar: "يترسب فلز على السطح." },
          explanation: { en: `${nameOf(a).en} is more reactive than ${saltMetal === "Hg" ? "mercury" : nameOf(deposit).en.toLowerCase()}, so it displaces it from the solution.`, ar: `${nameOf(a).ar} أنشط من ${nameOf(deposit).ar} فيحل محله في المحلول.` },
        });
      }
      return none(`${nameOf(a).en} is less reactive than the metal in the salt, so no displacement occurs.`, `${nameOf(a).ar} أقل نشاطاً من فلز الملح، فلا يحدث إحلال.`);
    }
  }

  // ---- oxides
  if (ca.kind === "oxide" || cb.kind === "oxide") return none("Basic metal oxides react with acids, not with salts or alkalis.", "أكاسيد الفلزات القاعدية تتفاعل مع الأحماض وليس مع الأملاح أو القلويات.");

  // ---- ionic + ionic
  if (isIonic(ca) && isIonic(cb)) return doubleDisplacement(a, ca, b, cb);
  return none("Physical mixture: no chemical reaction between these substances.", "خليط فيزيائي: لا يحدث تفاعل كيميائي بين هاتين المادتين.");
}

function ionicCountsOH(cat: string) {
  return CATIONS[cat]!.charge; // OH⁻ per formula unit (for ΔH scaling)
}

function doubleDisplacement(a: string, ca: Extract<Comp, { kind: "ionic" }>, b: string, cb: Extract<Comp, { kind: "ionic" }>): Outcome {
  if (!soluble(ca) || !soluble(cb)) return none("One of them is an insoluble solid, so its ions are not free to exchange — no reaction.", "إحدى المادتين صلب غير ذائب فلا تكون أيوناته حرة للتبادل — لا يحدث تفاعل.");
  if (ca.cat === cb.cat || ca.an === cb.an) return none("They share an ion, so exchanging partners gives the same substances — no reaction.", "تشتركان في أيون، فتبادل الأيونات يعطي المواد نفسها — لا يحدث تفاعل.");
  const p1 = { cat: ca.cat, an: cb.an };
  const p2 = { cat: cb.cat, an: ca.an };
  // Ammonium salt + strong base → ammonia gas
  for (const [x, y] of [[ca, cb], [cb, ca]] as const) {
    if (x.cat === "NH4" && y.an === "OH" && y.cat !== "NH4") {
      const salt = ionicId(y.cat, x.an);
      return build(`nh3:${a}:${b}`, ["double-displacement"], [a, b], [salt, "nh3", "water"], {
        gas: "nh3",
        thermal: "endothermic",
        explanation: { en: "A strong base releases ammonia gas (pungent smell) from an ammonium salt — the test for NH₄⁺.", ar: "القاعدة القوية تطلق غاز النشادر (رائحة نفاذة) من ملح الأمونيوم — كشف أيون الأمونيوم." },
      });
    }
  }
  const s1 = solubility(p1.cat, p1.an);
  const s2 = solubility(p2.cat, p2.an);
  if (s1.soluble && s2.soluble)
    return none("All possible products are soluble, so the ions simply stay in solution — no precipitate, no reaction.", "كل النواتج المحتملة ذائبة، فتبقى الأيونات في المحلول — لا راسب ولا تفاعل.");
  const id1 = p1.cat === "H" ? ionicId("H", p1.an) : ionicId(p1.cat, p1.an);
  const id2 = ionicId(p2.cat, p2.an);
  const ppt = !s1.soluble ? id1 : id2;
  const products = [id1, id2];
  // Silver/mercury hydroxides dehydrate to the oxide immediately.
  return build(`ppt:${a}:${b}`, ["precipitation", "double-displacement"], [a, b], products, {
    precipitate: ppt,
    thermal: "slight",
    colorChange: precipitateText(ppt),
    explanation: {
      en: `The ions swap partners; ${nameOf(ppt).en.toLowerCase()} is insoluble${(!s1.soluble && s1.slight) || (!s2.soluble && s2.slight) ? " (sparingly soluble)" : ""}, so it comes out of solution as a solid.`,
      ar: `تتبادل الأيونات مواقعها؛ و${nameOf(ppt).ar} غير ذائب${(!s1.soluble && s1.slight) || (!s2.soluble && s2.slight) ? " (شحيح الذوبان)" : ""} فينفصل عن المحلول كمادة صلبة.`,
    },
  });
}

/** A substance added to (or present in) water. Null = simply dissolves / mixes. */
export function waterOutcome(id: string): Outcome | null {
  const c = compositionOf(id);
  if (!c) return null;
  if (c.kind === "metal") {
    if (reactsWithColdWater(c.el)) {
      const hyd = ionicId(METAL_ION[c.el]!, "OH");
      return build(`water:${id}`, ["single-displacement", "redox"], [id, "water"], [hyd, "h2"], {
        gas: "h2",
        thermal: "exothermic",
        waterIsSolvent: true,
        explanation: { en: `${nameOf(id).en} is very reactive: it reacts with water to form ${nameOf(hyd).en.toLowerCase()} (alkaline) and hydrogen gas.`, ar: `${nameOf(id).ar} نشط جداً: يتفاعل مع الماء مكوناً ${nameOf(hyd).ar} (قلوي) وغاز الهيدروجين.` },
      });
    }
    return none(`${nameOf(id).en} does not react with cold water (it is below calcium in the activity series).`, `${nameOf(id).ar} لا يتفاعل مع الماء البارد (يلي الكالسيوم في متسلسلة النشاط).`);
  }
  if (c.kind === "oxide") {
    if (CATIONS[c.cat]!.group1 || c.cat === "Ca" || c.cat === "Ba") {
      const hyd = ionicId(c.cat, "OH");
      return build(`slake:${id}`, ["combination"], [id, "water"], [hyd], {
        thermal: "exothermic",
        waterIsSolvent: true,
        explanation: { en: `A basic oxide reacts with water to form an alkali: ${nameOf(hyd).en.toLowerCase()}. The mixture heats up.`, ar: `الأكسيد القاعدي يتفاعل مع الماء مكوناً قلوياً: ${nameOf(hyd).ar}. ويسخن الخليط.` },
      });
    }
    return none("This metal oxide is insoluble in water and does not react with it.", "أكسيد هذا الفلز لا يذوب في الماء ولا يتفاعل معه.");
  }
  if (c.kind === "ionic") {
    return solubility(c.cat, c.an).soluble
      ? none("It dissolves and separates into its ions (no new substance).", "يذوب وينفصل إلى أيوناته (دون تكوين مادة جديدة).")
      : none("It is insoluble in water and stays as a solid.", "لا يذوب في الماء ويبقى صلباً.");
  }
  return null;
}

/** Thermal decomposition of a dry solid (null when the substance is stable at this temperature). */
export function heatOutcome(id: string): { outcome: Outcome; minTempC: number } | null {
  const c = compositionOf(id);
  if (!c || c.kind !== "ionic" || c.cat === "H") return null;
  const C = CATIONS[c.cat]!;
  if (c.an === "CO3" && !C.group1) {
    const t = c.cat === "Ca" ? 840 : c.cat === "Ba" ? 1000 : c.cat === "Mg" ? 350 : 250;
    return {
      minTempC: t,
      outcome: build(`heat:${id}`, ["decomposition"], [id], [oxideId(c.cat), "co2"], { gas: "co2", thermal: "endothermic", minTempC: t, explanation: { en: `Thermal decomposition: the carbonate breaks down into ${nameOf(oxideId(c.cat)).en.toLowerCase()} and carbon dioxide.`, ar: `تحلل حراري: تتفكك الكربونات إلى ${nameOf(oxideId(c.cat)).ar} وثاني أكسيد الكربون.` } }),
    };
  }
  if (c.an === "HCO3" && C.group1) {
    const carb = ionicId(c.cat, "CO3");
    return { minTempC: 80, outcome: build(`heat:${id}`, ["decomposition"], [id], [carb, "water", "co2"], { gas: "co2", thermal: "endothermic", minTempC: 80, explanation: { en: "Hydrogen carbonates decompose on heating into the carbonate, water and carbon dioxide.", ar: "تتحلل البيكربونات بالتسخين إلى كربونات وماء وثاني أكسيد الكربون." } }) };
  }
  if (c.an === "OH" && !C.group1 && c.cat !== "Ba") {
    const t = c.cat === "Ca" ? 512 : c.cat === "Mg" ? 350 : 150;
    return { minTempC: t, outcome: build(`heat:${id}`, ["decomposition"], [id], [oxideId(c.cat), "water"], { thermal: "endothermic", minTempC: t, explanation: { en: `The hydroxide decomposes on heating into ${nameOf(oxideId(c.cat)).en.toLowerCase()} and water vapour.`, ar: `يتحلل الهيدروكسيد بالتسخين إلى ${nameOf(oxideId(c.cat)).ar} وبخار ماء.` } }) };
  }
  void ANIONS;
  return null;
}
